// ---------------------------------------------------------------------------
// QR golden vectors — generated by an INDEPENDENT implementation
// (Nayuki qrcodegen, forced byte mode, Ecc.MEDIUM, boost disabled)
// via scripts/research/gen_qr_vectors.py. Pico's encoder must
// reproduce every module, the version, and the chosen mask.
// ---------------------------------------------------------------------------

struct Vector {
    name: String,
    input: String,
    version: usize,
    mask: u8,
    rows: Vec<String>,
}

fn load_vectors() -> Vec<Vector> {
    let text = include_str!("qr_vectors.inc");
    let mut out = Vec::new();
    let mut cur: Option<Vector> = None;
    for line in text.lines() {
        if let Some(name) = line.strip_prefix("=== ") {
            if let Some(v) = cur.take() {
                out.push(v);
            }
            cur = Some(Vector {
                name: name.to_string(),
                input: String::new(),
                version: 0,
                mask: 0,
                rows: Vec::new(),
            });
        } else if let Some(v) = cur.as_mut() {
            if let Some(rest) = line.strip_prefix("input: ") {
                v.input = rest.to_string();
            } else if let Some(rest) = line.strip_prefix("version: ") {
                v.version = rest.parse().expect("vector version");
            } else if let Some(rest) = line.strip_prefix("mask: ") {
                v.mask = rest.parse().expect("vector mask");
            } else if line.starts_with("size: ") {
                // redundant with rows; skip
            } else if !line.is_empty() {
                v.rows.push(line.to_string());
            }
        }
    }
    if let Some(v) = cur.take() {
        out.push(v);
    }
    out
}

#[test]
fn qr_golden_vectors_match_module_for_module() {
    let vectors = load_vectors();
    // AUDIT V28 (A4-M3): the count is EXACT (a floor let the
    // set silently shrink), and the vectors cover every
    // version 1..=12 module-for-module — through v27 the top
    // version asserted only its number, not a single module.
    assert_eq!(vectors.len(), 17, "the pinned vector set");
    let mut versions: Vec<usize> = vectors.iter().map(|v| v.version).collect();
    versions.sort_unstable();
    versions.dedup();
    assert_eq!(
        versions,
        (1..=12).collect::<Vec<_>>(),
        "every version pinned"
    );
    for v in &vectors {
        let qr = encode_str(&v.input)
            .unwrap_or_else(|e| panic!("vector {} failed to encode: {e:?}", v.name));
        assert_eq!(qr.version, v.version, "vector {} version", v.name);
        assert_eq!(qr.mask, v.mask, "vector {} mask", v.name);
        assert_eq!(qr.size, v.rows.len(), "vector {} size", v.name);
        assert_eq!(qr.rows(), v.rows, "vector {} modules", v.name);
    }
}

#[test]
fn qr_capacity_and_error_edges() {
    // Empty is an error, never a blank symbol.
    assert_eq!(encode(b""), Err(QrError::Empty));
    // Exactly at v12-M capacity fits; one byte over does not.
    let at_cap = vec![b'a'; MAX_PAYLOAD_BYTES];
    let qr = encode(&at_cap).expect("287 bytes must fit v12-M");
    assert_eq!(qr.version, 12);
    let over = vec![b'a'; MAX_PAYLOAD_BYTES + 1];
    assert_eq!(
        encode(&over),
        Err(QrError::TooLong {
            bytes: MAX_PAYLOAD_BYTES + 1
        })
    );
    // Version selection is minimal: a 14-byte payload is v1,
    // 15 bytes is v2.
    assert_eq!(encode(&[b'x'; 14]).expect("v1").version, 1);
    assert_eq!(encode(&[b'x'; 15]).expect("v2").version, 2);
    // Multi-byte UTF-8 counts as BYTES (byte mode), not chars.
    let fa = "\u{631}".repeat(8); // 16 bytes in UTF-8.
    assert_eq!(encode_str(&fa).expect("utf8").version, 2);
}

#[test]
fn qr_symbol_invariants() {
    let qr = encode_str("https://example.com/").expect("encode");
    assert_eq!(qr.size, qr.version * 4 + 17);
    // Finder patterns: the three 7x7 corners' centers are dark,
    // and the top-left finder's ring structure holds.
    assert!(qr.get(3, 3) && qr.get(3, 0) && qr.get(0, 3));
    assert!(!qr.get(1, 1));
    // The always-dark module sits at (8, 4v+9).
    assert!(qr.get(8, 4 * qr.version + 9));
    // Timing patterns alternate, starting and ending dark.
    assert!(qr.get(8, 6) && qr.get(10, 6) && !qr.get(9, 6));
}

