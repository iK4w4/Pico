// AUDIT V26 D1: byte-exact transport. The teleport payload —
// display text AND QR content — is the tab's live URL exactly as
// the address bar shows it: no hop may normalize, canonicalize
// or re-parse it. (In v25 every Rust hop was already verbatim;
// the wrong value the user saw was the STALE stored URL — see
// the D7 chain test below. These pins keep the transport
// verbatim forever.)
