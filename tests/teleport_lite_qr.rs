#[test]
fn lite_decision_matrix() {
    // AUDIT V28 (A2 dead-seam sweep): this matrix used to run
    // against lite::decide — a boolean spec seam with no
    // production callers. It now runs against the pipeline the
    // browser actually uses (Shield off, no engine: Lite's
    // steps in isolation), so the matrix and the product can
    // never drift apart again.
    let lite_verdict = |lite_on: bool, class: ResourceType, page: &str, url: &str| {
        pipe_decide(
            &RequestFacts {
                url: url.to_string(),
                page_url: page.to_string(),
                rtype: class,
                method: Some("GET".to_string()),
                page_watch_shaped: pico_core::core::lite::is_watch_shaped_url(page),
                tab_chosen: false,
            },
            FilterState {
                shield_on: false,
                lite_on,
            },
            None,
        )
    };
    let heavy = [ResourceType::Image, ResourceType::Font, ResourceType::Media];
    let light = [
        ResourceType::Document,
        ResourceType::Subdocument,
        ResourceType::Script,
        ResourceType::Stylesheet,
        ResourceType::Xhr,
        ResourceType::WebSocket,
        ResourceType::Ping,
        ResourceType::Other,
    ];
    let public_page = "https://site.example/";
    let public_req = "https://cdn.example/file";
    let local_page = "http://127.0.0.1:5173/";
    let local_req = "http://127.0.0.1:9000/file";
    for class in heavy {
        assert!(is_lite_class(class));
        // On + public page + public request = block.
        assert_eq!(
            lite_verdict(true, class, public_page, public_req),
            Verdict::LiteBlock(class),
            "{class:?}"
        );
        // Local page OR local request always passes (hard law).
        assert_eq!(
            lite_verdict(true, class, local_page, public_req),
            Verdict::Allow,
            "{class:?} page-local"
        );
        assert_eq!(
            lite_verdict(true, class, public_page, local_req),
            Verdict::Allow,
            "{class:?} req-local"
        );
        assert_eq!(
            lite_verdict(true, class, local_page, local_req),
            Verdict::Allow,
            "{class:?} both-local"
        );
        // Off passes everything.
        assert_eq!(
            lite_verdict(false, class, public_page, public_req),
            Verdict::Allow,
            "{class:?} off"
        );
    }
    for class in light {
        assert!(!is_lite_class(class));
        assert_eq!(
            lite_verdict(true, class, public_page, public_req),
            Verdict::Allow,
            "{class:?} must pass"
        );
    }
}

