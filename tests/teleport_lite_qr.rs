fn lan() -> Option<Ipv4Addr> {
    Some("192.168.1.20".parse().expect("ip"))
}

#[test]
fn teleport_resolution_matrix() {
    // 1. Public https passes through unchanged.
    let t = resolve("https://example.com/page?x=1", lan(), false);
    assert_eq!(t.kind, TeleportKind::PublicUrl);
    assert_eq!(t.url.as_deref(), Some("https://example.com/page?x=1"));
    // 2. Public with a non-default port and query, unchanged.
    let t = resolve("http://news.site:8080/a/b?q=2#frag", lan(), false);
    assert_eq!(t.kind, TeleportKind::PublicUrl);
    assert_eq!(t.url.as_deref(), Some("http://news.site:8080/a/b?q=2#frag"));
    // 3. localhost dev URL -> LAN rewrite, port/path preserved.
    let t = resolve("http://localhost:5173/src/main", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.20:5173/src/main"));
    // 4. 127.0.0.1 without a port.
    let t = resolve("http://127.0.0.1/dashboard", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.20/dashboard"));
    // 5. The whole 127/8 block is loopback.
    let t = resolve("http://127.5.6.7:3000/", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    // 6. IPv6 loopback [::1] -> rewrite (brackets dropped, port kept).
    let t = resolve("http://[::1]:8080/app", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.20:8080/app"));
    // 7. 0.0.0.0 (dev servers print it) -> rewrite.
    let t = resolve("http://0.0.0.0:4200/", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.20:4200/"));
    // 8. Loopback but no LAN -> NoNetwork, original URL kept.
    let t = resolve("http://localhost:5173/", None, false);
    assert_eq!(t.kind, TeleportKind::NoNetwork);
    assert_eq!(t.url.as_deref(), Some("http://localhost:5173/"));
    // 9. Pico-served file pages are never rewritten.
    let t = resolve("http://127.0.0.1:49152/r/abc/page.html", lan(), true);
    assert_eq!(t.kind, TeleportKind::NotTeleportable);
    assert_eq!(t.url, None);
    // 10. The start page / internal scheme.
    let t = resolve("pico://start/", lan(), false);
    assert_eq!(t.kind, TeleportKind::NotTeleportable);
    // 11. file:// pages.
    let t = resolve("file:///C:/work/page.html", lan(), false);
    assert_eq!(t.kind, TeleportKind::NotTeleportable);
    // 12. about: and other non-web schemes.
    let t = resolve("about:blank", lan(), false);
    assert_eq!(t.kind, TeleportKind::NotTeleportable);
    // 13. Already a LAN address -> public (unchanged).
    let t = resolve("http://192.168.1.50:9000/x", lan(), false);
    assert_eq!(t.kind, TeleportKind::PublicUrl);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.50:9000/x"));
    // 14. Userinfo is not carried into a QR.
    let t = resolve("http://user:secret@localhost:3000/", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    assert_eq!(t.url.as_deref(), Some("http://192.168.1.20:3000/"));
    // 15. Query + fragment survive a rewrite byte-for-byte.
    let t = resolve("https://localhost:8443/a?b=c&d=%20#top", lan(), false);
    assert_eq!(
        t.url.as_deref(),
        Some("https://192.168.1.20:8443/a?b=c&d=%20#top")
    );
    // Notes are the researched strings.
    let t = resolve("http://localhost:5173/", lan(), false);
    assert!(t.note.contains("--host (Vite)"), "note: {}", t.note);
    assert!(t.note.contains("-H 0.0.0.0 (Next)"), "note: {}", t.note);
}

