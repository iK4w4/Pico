fn cand(ip: &str, up: bool) -> LanCandidate {
    // AUDIT 0.31 (A4-F2): the plain candidate is a physical,
    // non-duplicated address — the pre-0.31 shape, so the
    // historical pins below keep their meaning.
    LanCandidate {
        ip: ip.parse::<Ipv4Addr>().expect("ip"),
        up,
        kind: LanKind::Physical,
        dad_duplicate: false,
    }
}

fn cand_kind(ip: &str, up: bool, kind: LanKind, dad_duplicate: bool) -> LanCandidate {
    LanCandidate {
        ip: ip.parse::<Ipv4Addr>().expect("ip"),
        up,
        kind,
        dad_duplicate,
    }
}

#[test]
fn lan_chooser_filters_and_prefers() {
    // Nothing usable -> None.
    assert_eq!(choose_lan_ip(&[]), None);
    assert_eq!(
        choose_lan_ip(&[cand("127.0.0.1", true), cand("169.254.1.5", true)]),
        None
    );
    assert_eq!(choose_lan_ip(&[cand("0.0.0.0", true)]), None);
    // 192.168 beats 10 beats 172.16/12 beats public.
    let all = [
        cand("8.8.8.8", true),
        cand("172.16.0.5", true),
        cand("10.0.0.5", true),
        cand("192.168.1.5", true),
    ];
    assert_eq!(
        choose_lan_ip(&all),
        Some("192.168.1.5".parse().expect("ip"))
    );
    assert_eq!(
        choose_lan_ip(&all[..3]),
        Some("10.0.0.5".parse().expect("ip"))
    );
    assert_eq!(
        choose_lan_ip(&all[..2]),
        Some("172.16.0.5".parse().expect("ip"))
    );
    // 172.32 is NOT RFC1918 — it falls to the public tier.
    let mixed = [cand("172.32.0.5", true), cand("172.31.0.5", true)];
    assert_eq!(
        choose_lan_ip(&mixed),
        Some("172.31.0.5".parse().expect("ip"))
    );
    // Within a tier, an Up adapter beats a down one; equal keys
    // keep enumeration order.
    let tier = [cand("192.168.1.5", false), cand("192.168.1.9", true)];
    assert_eq!(
        choose_lan_ip(&tier),
        Some("192.168.1.9".parse().expect("ip"))
    );
    let order = [cand("192.168.1.5", true), cand("192.168.1.9", true)];
    assert_eq!(
        choose_lan_ip(&order),
        Some("192.168.1.5".parse().expect("ip"))
    );
}

#[test]
fn v28_lan_chooser_up_beats_tier_and_egress_wins() {
    // A4-M1: through v27 the RFC1918 tier dominated the up
    // flag — a DOWN 192.168 adapter beat the live 10.x Wi-Fi.
    // Liveness is the first key now.
    let mixed = [cand("192.168.1.5", false), cand("10.0.0.5", true)];
    assert_eq!(choose_lan_ip(&mixed), Some("10.0.0.5".parse().expect("ip")));
    // An egress address among the candidates wins outright,
    // whatever its tier or state — it is the OS's own route.
    let cands = [cand("192.168.1.5", true), cand("10.0.0.5", true)];
    assert_eq!(
        choose_lan_ip_with_egress(&cands, Some("10.0.0.5".parse().expect("ip"))),
        Some("10.0.0.5".parse().expect("ip"))
    );
    // An egress NOT among the usable candidates is ignored
    // (stale probe, VPN gone): the key order decides.
    assert_eq!(
        choose_lan_ip_with_egress(&cands, Some("172.16.0.9".parse().expect("ip"))),
        Some("192.168.1.5".parse().expect("ip"))
    );
    // An unusable egress (loopback) never wins.
    assert_eq!(
        choose_lan_ip_with_egress(&cands, Some("127.0.0.1".parse().expect("ip"))),
        Some("192.168.1.5".parse().expect("ip"))
    );
}

#[test]
fn v28_teleport_hardening_matrix() {
    // A4-M4: public URLs drop userinfo too (the rewrite path
    // always did); everything else stays byte-exact, and an
    // '@' in the PATH is not userinfo.
    let t = resolve("https://user:secret@example.com/x?y=1", lan(), false);
    assert_eq!(t.kind, TeleportKind::PublicUrl);
    assert_eq!(t.url.as_deref(), Some("https://example.com/x?y=1"));
    let t = resolve("https://example.com/@user/page", lan(), false);
    assert_eq!(t.url.as_deref(), Some("https://example.com/@user/page"));
    // A4-L1: trailing-dot loopback is loopback.
    let t = resolve("http://localhost.:5173/", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    let t = resolve("http://127.0.0.1.:3000/", lan(), false);
    assert_eq!(t.kind, TeleportKind::LanRewrite);
    // A4-L3: invalid ports cannot be rewritten — the panel
    // says "can't teleport" instead of printing a dead QR.
    for bad in [
        "http://localhost:0/",
        "http://localhost:99999/",
        "http://localhost:abc/",
    ] {
        let t = resolve(bad, lan(), false);
        assert_eq!(t.kind, TeleportKind::NotTeleportable, "{bad}");
    }
    // A4-L5: only LanRewrite/PublicUrl URLs are QR-encodable.
    let t = resolve("http://localhost:5173/", None, false);
    assert_eq!(t.kind, TeleportKind::NoNetwork);
    assert!(t.url.is_some(), "display keeps the original URL");
    assert_eq!(t.qr_url(), None, "but nothing may be encoded");
    let t = resolve("https://example.com/", lan(), false);
    assert_eq!(t.qr_url(), Some("https://example.com/"));
    let t = resolve("http://localhost:5173/", lan(), false);
    assert_eq!(t.qr_url(), Some("http://192.168.1.20:5173/"));
    let t = resolve("pico://start/", lan(), false);
    assert_eq!(t.qr_url(), None);
    // A4-L2: non-web schemes are NotTeleportable by RULE, not
    // by accident — pinned so a future parser change can't
    // quietly start teleporting them.
    for scheme_url in [
        "data:text/html,<h1>x</h1>",
        "blob:https://example.com/1234",
        "view-source:https://example.com/",
        "javascript:alert(1)",
    ] {
        let t = resolve(scheme_url, lan(), false);
        assert_eq!(t.kind, TeleportKind::NotTeleportable, "{scheme_url}");
    }
}

