#[test]
fn state_v24_file_loads_with_lite_off() {
    let dir = std::env::temp_dir().join(format!("pico-v25-state-{}", std::process::id()));
    let _ = std::fs::create_dir_all(&dir);
    let path = dir.join("state.json");
    // A verbatim v24-shaped file: schema 3, recents_hidden, no lite_on.
    std::fs::write(
        &path,
        r#"{"version":3,"theme":"dark","recents":[],"shield_on":true,"blocked_total":7,"recents_hidden":true}"#,
    )
    .expect("write state");
    match load_from_checked(&path) {
        LoadOutcome::Loaded(state) => {
            assert!(!state.lite_on, "lite must default OFF for old files");
            assert!(state.recents_hidden);
            assert_eq!(state.blocked_total, 7);
        }
        other => panic!("expected Loaded, got {other:?}"),
    }
    // And a v25 file round-trips lite_on=true.
    let mut state = pico_core::core::state::PersistState {
        lite_on: true,
        ..Default::default()
    };
    state.theme = "dark".to_string();
    pico_core::core::state::save_to(&path, &state).expect("save");
    match load_from_checked(&path) {
        LoadOutcome::Loaded(loaded) => assert!(loaded.lite_on),
        other => panic!("expected Loaded, got {other:?}"),
    }
    let _ = std::fs::remove_dir_all(&dir);
}

